-- ------------------------------------------------------------
-- Stop functions, called by the backend through .rpc()
-- ------------------------------------------------------------
-- Inserting or deleting a stop shifts the sira_no of every later stop on the same route.
-- Doing that in one function call keeps it in a single transaction and locks the route's
-- stops, so two admins editing the same route at once cannot produce duplicate or missing
-- sequence numbers.

CREATE OR REPLACE FUNCTION public.atomik_durak_ekle(p_guzergah_id uuid, p_firma_id uuid, p_durak_adi text, p_konum_lat numeric, p_konum_lng numeric, p_sira_no integer)
 RETURNS TABLE(id uuid, durak_adi text, sira_no integer)
 LANGUAGE plpgsql
AS $function$
BEGIN
    -- Lock the other stops on this route (prevents a race condition)
    PERFORM 1 FROM duraklar
    WHERE duraklar.guzergah_id = p_guzergah_id
    FOR UPDATE;

    -- Qualify sira_no with "duraklar." so it is not confused with the sira_no in RETURNS TABLE
    UPDATE duraklar
    SET sira_no = duraklar.sira_no + 1
    WHERE duraklar.guzergah_id = p_guzergah_id
      AND duraklar.sira_no >= p_sira_no;

    -- Insert the new stop and return it
    RETURN QUERY
    INSERT INTO duraklar (guzergah_id, firma_id, durak_adi, konum_lat, konum_lng, sira_no)
    VALUES (p_guzergah_id, p_firma_id, p_durak_adi, p_konum_lat, p_konum_lng, p_sira_no)
    RETURNING duraklar.id, duraklar.durak_adi, duraklar.sira_no;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.atomik_durak_sil(p_durak_id uuid)
 RETURNS TABLE(silinen_durak_id uuid, kalan_durak_sayisi integer)
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_guzergah_id UUID;
    v_silinen_sira INTEGER;
    v_kalan_sayi INTEGER;
BEGIN
    -- 1. Read the route and sequence number of the stop being deleted
    SELECT guzergah_id, sira_no INTO v_guzergah_id, v_silinen_sira
    FROM duraklar
    WHERE id = p_durak_id;

    IF v_guzergah_id IS NULL THEN
        RAISE EXCEPTION 'Durak bulunamadı: %', p_durak_id;
    END IF;

    -- 2. Lock the other stops on this route (prevents a race condition)
    PERFORM 1 FROM duraklar
    WHERE guzergah_id = v_guzergah_id
    FOR UPDATE;

    -- 3. Delete the stop
    DELETE FROM duraklar WHERE id = p_durak_id;

    -- 4. Move every later stop up by one
    UPDATE duraklar
    SET sira_no = sira_no - 1
    WHERE guzergah_id = v_guzergah_id
      AND sira_no > v_silinen_sira;

    -- 5. Return how many stops are left
    SELECT COUNT(*) INTO v_kalan_sayi
    FROM duraklar
    WHERE guzergah_id = v_guzergah_id;

    RETURN QUERY SELECT p_durak_id, v_kalan_sayi::INTEGER;
END;
$function$
;


-- ------------------------------------------------------------
-- Clean-up functions
-- ------------------------------------------------------------
-- Each deletes old rows and returns how many it deleted. Neither the backend nor any pg_cron
-- job calls them (checked 2026-10-02); they are kept because they exist in the live database.

-- Audit log entries older than 6 months.
CREATE OR REPLACE FUNCTION public.eski_audit_loglarini_temizle()
 RETURNS integer
 LANGUAGE plpgsql
AS $function$
DECLARE
    silinen_sayi INTEGER;
BEGIN
    DELETE FROM audit_log WHERE tarih < NOW() - INTERVAL '6 months';
    GET DIAGNOSTICS silinen_sayi = ROW_COUNT;
    RETURN silinen_sayi;
END;
$function$
;

-- Revoked tokens that have expired anyway (an expired token is rejected without the list).
CREATE OR REPLACE FUNCTION public.expire_olan_revoked_temizle()
 RETURNS integer
 LANGUAGE plpgsql
AS $function$
DECLARE
    silinen_sayi INTEGER;
BEGIN
    DELETE FROM revoked_tokens WHERE expire_tarihi < NOW();
    GET DIAGNOSTICS silinen_sayi = ROW_COUNT;
    RETURN silinen_sayi;
END;
$function$
;
