-- ============================================================
-- Base schema: every table and database function the backend uses
-- ============================================================
-- Exported from the live database on 2026-10-02 (public schema only, structure only, no data)
-- and tidied without changing behaviour: indexes that duplicated another index or a key were
-- dropped, and leftover defaults were removed from foreign key columns (the backend always
-- sets them; a random uuid there could never satisfy the foreign key anyway).
-- Tables are ordered so that each one is created after the tables it references.
--
-- Fresh install: run this file once in the Supabase SQL editor, then run only the pg_cron
-- steps (the scheduled clean-up jobs) of kvkk_temizlik.sql (two jobs), kvkk_riza.sql and
-- memnuniyet_anketleri.sql. gorev_etaplari.sql also describes an optional job that is off on
-- purpose. Everything else in the db/*.sql files is a migration for older databases and is
-- already included here.
--
-- Row level security is enabled on every table and there are no policies. That is deliberate:
-- the backend connects with the service_role key, which bypasses RLS, and the browser never
-- talks to the database directly, so the public (anon) key can read nothing.
-- ============================================================


